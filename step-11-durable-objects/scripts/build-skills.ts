/**
 * npm run build:skills
 *
 * Packs every file under skills/ into src/skills/generated.ts (git-ignored), as
 * { "monthly-sales-review/SKILL.md": "...", ... }. A Worker has no file system, so the
 * skill files travel inside the bundle, and the SDK's skill catalog serves them from
 * memory. Edit the files in skills/, never the generated module.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..", "skills");
const files: Record<string, string> = {};
const walk = (dir: string) => {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else files[relative(root, path).split("\\").join("/")] = readFileSync(path, "utf8");
  }
};
walk(root);

writeFileSync(
  join(import.meta.dirname, "..", "src", "skills", "generated.ts"),
  "// GENERATED by scripts/build-skills.ts from skills/. Do not edit; run npm run build:skills.\n" +
    `export const SKILL_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(`Packed ${Object.keys(files).length} skill file(s) into src/skills/generated.ts.`);
