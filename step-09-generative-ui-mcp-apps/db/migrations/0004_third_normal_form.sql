-- 0004: THIRD NORMAL FORM (3NF): the design the server's tools use.
--
-- Rule: no column depends on another NON-key column. Each fact lives once, in the table
-- it describes.
-- Broken by:
--   * staging.orders_2nf: customer_name and customer_city depend on customer_email,
--     not on the order. Ayesha's city is stored on every order, so it can disagree.
--   * staging.order_lines_2nf: category depends on product_name, not on the line.
--     The same category is typed again on every line ("accessories " vs "Accessories").
-- Fix: customers, categories and products become their own tables; orders and lines
-- point at them by key.
--
-- A COPY ON PURPOSE: order_items.unit_price repeats a price that also lives in
-- products.list_price. That breaks 3NF deliberately: an invoice must keep the price the
-- customer actually paid, even after the catalog price changes.
--
-- MULTI-TENANT KEYS (book lesson 19.7): every table carries org_id, every primary key
-- starts with org_id, and every foreign key includes org_id. So a row can never point at
-- another company's row: the database itself refuses it.

CREATE TABLE categories (
  org_id      text   NOT NULL,
  category_id bigint GENERATED BY DEFAULT AS IDENTITY,
  name        text   NOT NULL CHECK (length(name) BETWEEN 1 AND 60 AND name = trim(name)),
  PRIMARY KEY (org_id, category_id),
  UNIQUE (org_id, name)
);

CREATE TABLE products (
  org_id      text          NOT NULL,
  product_id  bigint        GENERATED BY DEFAULT AS IDENTITY,
  category_id bigint        NOT NULL,
  name        text          NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
  list_price  numeric(10,2) NOT NULL CHECK (list_price >= 0),  -- today's catalog price
  PRIMARY KEY (org_id, product_id),
  UNIQUE (org_id, name),
  FOREIGN KEY (org_id, category_id) REFERENCES categories (org_id, category_id)
);

CREATE TABLE customers (
  org_id      text   NOT NULL,
  customer_id bigint GENERATED BY DEFAULT AS IDENTITY,
  name        text   NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
  email       text   NOT NULL CHECK (email LIKE '%_@_%'),
  city        text   NOT NULL,
  PRIMARY KEY (org_id, customer_id),
  UNIQUE (org_id, email)
);

CREATE TABLE orders (
  org_id      text   NOT NULL,
  order_id    bigint GENERATED BY DEFAULT AS IDENTITY,
  order_ref   text   NOT NULL,
  customer_id bigint NOT NULL,
  order_date  date   NOT NULL,
  PRIMARY KEY (org_id, order_id),
  UNIQUE (org_id, order_ref),
  FOREIGN KEY (org_id, customer_id) REFERENCES customers (org_id, customer_id)
);

CREATE TABLE order_items (
  org_id     text          NOT NULL,
  order_id   bigint        NOT NULL,
  line_no    integer       NOT NULL CHECK (line_no > 0),
  product_id bigint        NOT NULL,
  quantity   integer       NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),  -- the copy on purpose
  PRIMARY KEY (org_id, order_id, line_no),
  FOREIGN KEY (org_id, order_id) REFERENCES orders (org_id, order_id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, product_id) REFERENCES products (org_id, product_id)
);

-- Indexes for the joins and filters the tools run, always led by org_id.
CREATE INDEX orders_customer_idx ON orders (org_id, customer_id);
CREATE INDEX orders_date_idx ON orders (org_id, order_date);
CREATE INDEX order_items_product_idx ON order_items (org_id, product_id);

-- ---------------------------------------------------------------------------------
-- Move the data. Each step cleans one kind of repeated fact.
-- ---------------------------------------------------------------------------------

-- Categories: one row per category, with the spelling cleaned up once.
INSERT INTO categories (org_id, name)
SELECT DISTINCT org_id, initcap(lower(trim(category)))
FROM staging.order_lines_2nf
ORDER BY 1, 2;

-- Products: one row per product. Its catalog price is the most recent price it sold at.
INSERT INTO products (org_id, category_id, name, list_price)
SELECT DISTINCT ON (l.org_id, l.product_name)
       l.org_id, c.category_id, l.product_name, l.unit_price
FROM staging.order_lines_2nf l
JOIN staging.orders_2nf o USING (org_id, order_ref)
JOIN categories c ON c.org_id = l.org_id AND c.name = initcap(lower(trim(l.category)))
ORDER BY l.org_id, l.product_name, o.order_date DESC, l.order_ref DESC;

-- A new product added to the catalog before anyone has bought it. The flat sheet had no
-- way to record this without inventing an order (an INSERT anomaly). Now it's one row.
INSERT INTO products (org_id, category_id, name, list_price)
SELECT 'demo', category_id, 'Monitor Arm', 79.00
FROM categories WHERE org_id = 'demo' AND name = 'Accessories';

-- Customers: one row per email. Their name and city come from their MOST RECENT order,
-- which settles Ayesha's two cities: she lives in Karachi now.
INSERT INTO customers (org_id, name, email, city)
SELECT DISTINCT ON (org_id, customer_email)
       org_id, customer_name, customer_email, customer_city
FROM staging.orders_2nf
ORDER BY org_id, customer_email, order_date DESC, order_ref DESC;

-- Orders: the order-level facts, pointing at the customer by key.
INSERT INTO orders (org_id, order_ref, customer_id, order_date)
SELECT o.org_id, o.order_ref, c.customer_id, o.order_date
FROM staging.orders_2nf o
JOIN customers c ON c.org_id = o.org_id AND c.email = o.customer_email
ORDER BY o.org_id, o.order_ref;

-- Order items: the line-level facts, pointing at the order and the product by key,
-- and keeping the price actually paid.
INSERT INTO order_items (org_id, order_id, line_no, product_id, quantity, unit_price)
SELECT l.org_id, o.order_id, l.line_no, p.product_id, l.quantity, l.unit_price
FROM staging.order_lines_2nf l
JOIN orders o ON o.org_id = l.org_id AND o.order_ref = l.order_ref
JOIN products p ON p.org_id = l.org_id AND p.name = l.product_name;
