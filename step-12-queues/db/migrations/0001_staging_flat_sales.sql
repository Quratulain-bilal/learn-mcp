orders AS (
  SELECT i,
         'SO-' || lpad(i::text, 4, '0')       AS order_ref,
         date '2025-01-02' + (i * 360) / 145  AS order_date,  -- spread over the year
         1 + (i * 7) % 15                     AS customer_n
  FROM generate_series(1, 140) AS i
),
lines AS (
  SELECT o.*, l AS line_no,
         1 + (o.i * 5 + l * 3) % 11 AS product_n,
         1 + (o.i + l) % 4          AS qty
  FROM orders o
  CROSS JOIN LATERAL generate_series(1, 1 + o.i % 3) AS l
)
INSERT INTO staging.flat_sales
  (org_id, order_ref, order_date, customer_name, customer_email, customer_city,
   products, category, unit_price, quantity)
SELECT 'demo', l.order_ref, l.order_date, c.name, c.email, c.city,
       p.name, p.category,
       to_char(CASE WHEN l.order_date < date '2025-07-01' THEN p.price_h1 ELSE p.price_h2 END, 'FM999990.00'),
       l.qty::text
FROM lines l
JOIN customers c ON c.n = l.customer_n
JOIN products p ON p.n = l.product_n
ORDER BY l.i, l.line_no;

