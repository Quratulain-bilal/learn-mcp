-- 0001: the flat sales spreadsheet, loaded as-is into a `staging` schema.
--
-- This is what a client usually hands you: one row per order line, with the customer's
-- details and the product's details repeated on every row. Some cells even hold several
-- products ("Desk Lamp; LED Bulb Pack"). We keep it in `staging` so you can query it,
-- see what goes wrong, and compare it with the normalized design (migrations 0002-0004).
--
-- Every row belongs to a company (org_id). The sample data goes into the demo company
-- 'demo'; `npm run db:seed` copies it into your own company.

CREATE SCHEMA IF NOT EXISTS staging;

CREATE TABLE staging.flat_sales (
  line_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         text NOT NULL,
  order_ref      text NOT NULL,       -- e.g. SO-0042, repeated on every line of the order
  order_date     date NOT NULL,
  customer_name  text NOT NULL,       -- repeated on every line of every order
  customer_email text NOT NULL,
  customer_city  text NOT NULL,
  products       text NOT NULL,       -- sometimes several products: "A; B"  (breaks 1NF)
  category       text NOT NULL,       -- one per product, in the same order:  "X; Y"
  unit_price     text NOT NULL,       -- text, because a cell can hold "24.00; 6.50"
  quantity       text NOT NULL        -- text, because a cell can hold "1; 3"
);

